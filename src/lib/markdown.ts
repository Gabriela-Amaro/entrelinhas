import MarkdownIt from 'markdown-it';
import anchor from 'markdown-it-anchor';
import footnote from 'markdown-it-footnote';
import taskLists from 'markdown-it-task-lists';
import texmath from 'markdown-it-texmath';
import { full as emoji } from 'markdown-it-emoji';
import sub from 'markdown-it-sub';
import sup from 'markdown-it-sup';
import mark from 'markdown-it-mark';
import ins from 'markdown-it-ins';
import deflist from 'markdown-it-deflist';
import katex from 'katex';
import hljs from 'highlight.js';
import DOMPurify from 'dompurify';

export interface Heading { id: string; text: string; level: number }
export const md = new MarkdownIt({
  html: true, linkify: true, typographer: true,
  highlight(code, language) {
    if (language && hljs.getLanguage(language)) return hljs.highlight(code, { language, ignoreIllegals: true }).value;
    return '';
  },
}).use(anchor).use(footnote).use(taskLists, { enabled: true, label: true })
  .use(texmath, { engine: katex, delimiters: 'dollars', katexOptions: { throwOnError: false, trust: false, strict: 'ignore' } })
  .use(emoji).use(sub).use(sup).use(mark).use(ins).use(deflist);

md.core.ruler.after('github-task-lists', 'task-source-lines', state => {
  for (const token of state.tokens) {
    if (token.type !== 'inline' || !token.map) continue;
    for (const child of token.children || []) {
      if (child.type === 'html_inline' && child.content.includes('class="task-list-item-checkbox"')) {
        child.content = child.content.replace('<input ', `<input data-task-line="${token.map[0] + Number(state.env.lineOffset || 0)}" `);
      }
    }
  }
});

export function toggleTask(source: string, line: number, checked: boolean): string {
  const lines = source.split('\n');
  if (!Number.isInteger(line) || line < 0 || line >= lines.length) return source;
  lines[line] = lines[line].replace(/\[[ xX]\](?=\s|$)/, checked ? '[x]' : '[ ]');
  return lines.join('\n');
}

// Preserve HTML nesting (details, summary, kbd) while stripping authored styles.
// The complete rendered document is sanitized below; KaTeX keeps its own styles.
for (const rule of ['html_block', 'html_inline']) {
  md.renderer.rules[rule] = (tokens, index) => tokens[index].content.replace(/\sstyle\s*=\s*(?:"[^"]*"|'[^']*'|[^\s>]+)/gi, '');
}

const defaultFence = md.renderer.rules.fence!;
md.renderer.rules.fence = (tokens, index, options, env, self) => {
  const token = tokens[index];
  const language = token.info.trim().split(/\s+/)[0];
  if (language === 'mermaid') return `<div class="mermaid-block" data-mermaid="${encodeURIComponent(token.content)}"><div class="diagram-loading">Preparando diagrama…</div></div>`;
  return `<div class="code-block"><div class="code-header"><span>${md.utils.escapeHtml(language || 'texto')}</span></div>${defaultFence(tokens, index, options, env, self)}</div>`;
};
const defaultImage = md.renderer.rules.image!;
md.renderer.rules.image = (tokens, index, options, env, self) => {
  const token = tokens[index];
  const src = String(token.attrGet('src') || '');
  if (!/^(https?:|data:|blob:)/i.test(src)) { token.attrSet('data-local-src', src); token.attrSet('src', ''); }
  token.attrSet('loading', 'lazy');
  return defaultImage(tokens, index, options, env, self);
};

export function renderMarkdown(source: string): { html: string; headings: Heading[]; metadata: Record<string, string> } {
  const metadata: Record<string, string> = {};
  let lineOffset = 0;
  let text = source.replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
  text = text.replace(/^---\n([\s\S]*?)\n---(?:\n|$)/, (_all, frontmatter: string) => {
    lineOffset = _all.split('\n').length - 1;
    for (const line of frontmatter.split('\n')) {
      const match = line.match(/^([^:#]+):\s*(.+)$/);
      if (match) metadata[match[1].trim()] = match[2].trim().replace(/^['"]|['"]$/g, '');
    }
    return '';
  });
  let html = md.render(text, { lineOffset });
  html = html.replace(/<blockquote>\s*<p>\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]\s*/g, (_all, kind: string) => {
    const labels: Record<string, string> = { NOTE: 'Nota', TIP: 'Dica', IMPORTANT: 'Importante', WARNING: 'Atenção', CAUTION: 'Cuidado' };
    return `<blockquote class="callout callout-${kind.toLowerCase()}"><p><strong class="callout-label">${labels[kind]}</strong>`;
  });
  html = DOMPurify.sanitize(html, {
    ADD_TAGS: ['eq', 'eqn'], ADD_ATTR: ['target'],
    FORBID_TAGS: ['style', 'script', 'iframe', 'form', 'button', 'textarea', 'select', 'video', 'audio', 'object', 'embed'],
    // Only the buttons generated by the renderer are added below after sanitization.
    FORBID_ATTR: ['srcdoc'],
  });
  const container = document.createElement('div');
  container.innerHTML = html;
  container.querySelectorAll('.code-header').forEach(header => {
    const button = document.createElement('button'); button.type = 'button'; button.className = 'copy-code'; button.textContent = 'Copiar'; button.setAttribute('aria-label', 'Copiar código'); header.append(button);
  });
  // Raw HTML images receive the same local asset handling as Markdown images.
  container.querySelectorAll('img[src]').forEach(image => {
    const src = image.getAttribute('src') || '';
    if (src && !/^(https?:|data:|blob:)/i.test(src)) { image.setAttribute('data-local-src', src); image.removeAttribute('src'); }
  });
  container.querySelectorAll('a').forEach(link => { link.setAttribute('rel', 'noopener noreferrer'); });
  const headings: Heading[] = [];
  container.querySelectorAll('h1,h2,h3,h4,h5,h6').forEach((heading, index) => {
    if (!heading.id) heading.id = `section-${index}`;
    headings.push({ id: heading.id, text: heading.textContent || '', level: Number(heading.tagName[1]) });
  });
  return { html: container.innerHTML, headings, metadata };
}
